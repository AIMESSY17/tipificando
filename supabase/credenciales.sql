-- tipificado… | Credenciales de Mercado Pago cargadas desde el panel
-- Pegar entero en Supabase → SQL Editor → Run, DESPUÉS de schema.sql.
-- No borra nada y se puede correr más de una vez.
--
-- · credenciales: una fila por credencial ('mp_access_token' y 'mp_webhook_secret').
--   El valor llega ya CIFRADO por el servidor (AES-256-GCM con CREDENCIALES_KEY, que vive solo
--   en Vercel): acá nunca hay texto plano. valor_cifrado = v1.<huella de la clave>.<iv>.<tag>.<cifrado>
--   ultimos4, cuenta_* y es_prueba son lo único que el panel muestra.
-- · credenciales_cambios: quién y cuándo cambió cada credencial (y el modo prueba). Sin valores.
--   No se puede editar ni borrar.
-- · RLS activada y SIN políticas, y sin permisos para anon/authenticated: el navegador no las
--   puede leer ni escribir, ni siquiera con la sesión de un admin. Solo el servidor (service role).
-- =========================================================

-- ---------- Credenciales (cifradas) ----------
create table if not exists credenciales (
  proveedor text primary key,
  valor_cifrado text not null,
  ultimos4 text not null default '',
  cuenta_nombre text,            -- nombre y apellido de la cuenta de Mercado Pago (solo el token)
  cuenta_apodo text,             -- nickname (TESTUSER… en las cuentas de prueba)
  cuenta_id text,                -- id de usuario de Mercado Pago
  es_prueba boolean not null default false,
  actualizado_por text not null default '',
  actualizado_en timestamptz not null default now()
);
-- por si la tabla ya existía de una prueba anterior
alter table credenciales add column if not exists ultimos4 text not null default '';
alter table credenciales add column if not exists cuenta_nombre text;
alter table credenciales add column if not exists cuenta_apodo text;
alter table credenciales add column if not exists cuenta_id text;
alter table credenciales add column if not exists es_prueba boolean not null default false;
alter table credenciales add column if not exists actualizado_por text not null default '';
alter table credenciales add column if not exists actualizado_en timestamptz not null default now();

alter table credenciales drop constraint if exists credenciales_proveedor_check;
alter table credenciales add constraint credenciales_proveedor_check
  check (proveedor in ('mp_access_token', 'mp_webhook_secret'));
-- nunca texto plano: solo el formato que arma el servidor
alter table credenciales drop constraint if exists credenciales_cifrado_check;
alter table credenciales add constraint credenciales_cifrado_check
  check (valor_cifrado ~ '^v1\.[0-9a-f]{8}\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$');
alter table credenciales drop constraint if exists credenciales_ultimos4_check;
alter table credenciales add constraint credenciales_ultimos4_check check (char_length(ultimos4) <= 4);

-- ---------- Registro de cambios (sin valores) ----------
create table if not exists credenciales_cambios (
  id bigint generated by default as identity primary key,
  proveedor text not null,       -- mp_access_token | mp_webhook_secret | mp_modo_prueba
  accion text not null,          -- cargado | cambiado | activado | desactivado
  ultimos4 text not null default '',
  cuenta_nombre text,
  es_prueba boolean,
  hecho_por text not null default '',
  hecho_en timestamptz not null default now()
);
create index if not exists credenciales_cambios_fecha_idx on credenciales_cambios (hecho_en desc);

-- El registro no se edita ni se borra (ni siquiera desde el servidor)
create or replace function credenciales_cambios_fijo() returns trigger
language plpgsql set search_path = public as $$
begin
  raise exception 'El registro de cambios de credenciales no se puede editar ni borrar';
end $$;
drop trigger if exists credenciales_cambios_fijo on credenciales_cambios;
create trigger credenciales_cambios_fijo before update or delete on credenciales_cambios
  for each row execute function credenciales_cambios_fijo();

-- ---------- Seguridad ----------
alter table credenciales enable row level security;
alter table credenciales_cambios enable row level security;

-- SIN políticas, a propósito. Si alguien agregó una a mano, se borra.
do $$
declare p record;
begin
  for p in select policyname, tablename from pg_policies
            where schemaname = 'public' and tablename in ('credenciales', 'credenciales_cambios') loop
    execute format('drop policy %I on %I', p.policyname, p.tablename);
  end loop;
end $$;

-- Supabase da permisos a anon y authenticated sobre cada tabla nueva: se sacan (doble candado).
revoke all on table credenciales, credenciales_cambios from public, anon, authenticated;
grant select, insert, update, delete on table credenciales to service_role;
grant select, insert on table credenciales_cambios to service_role;
revoke update, delete, truncate on table credenciales_cambios from service_role;
do $$
declare s text := pg_get_serial_sequence('credenciales_cambios', 'id');
begin
  if s is not null then
    execute format('revoke all on sequence %s from public, anon, authenticated', s);
    execute format('grant usage, select on sequence %s to service_role', s);
  end if;
end $$;

