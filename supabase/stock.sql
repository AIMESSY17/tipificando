-- =========================================================
-- tipificado… | Control de stock
-- Pegar entero en Supabase → SQL Editor → Run, DESPUÉS de schema.sql.
-- No borra nada: todas las piezas quedan «sin control» (stock = null, como hasta ahora)
-- hasta que el dueño cargue números desde el panel. Se puede correr más de una vez.
--
-- Cómo funciona:
--   · products.stock: unidades disponibles (null = sin control). Nunca baja de 0.
--   · Al crear un pedido (crear_pedido → insert en orders) un trigger bloquea las piezas
--     (FOR UPDATE), verifica que alcance y las descuenta como RESERVA. Si no alcanza, el pedido
--     no se crea (error 'sin_stock' con las piezas que faltan, sin números).
--   · Pedido pagado (Mercado Pago o a mano en el panel) → la reserva queda como VENTA.
--   · Pedido rechazado / cancelado / devuelto mientras estaba reservado → vuelve al stock solo.
--   · Reserva vencida (reserva_vence_at) → vuelve al stock sola (liberar_reservas_vencidas:
--     al crear pedidos, al leer el catálogo, con pg_cron cada 5 min y con el cron de Vercel).
--     Nunca devuelve dos veces: cada pedido pasa de 'reservado' a 'liberado' una sola vez.
--   · Una venta ya hecha que se cancela vuelve al stock solo si el dueño lo elige en el panel.
--   · Cada cambio queda en stock_movimientos (solo lo ven los admins).
-- =========================================================

-- ---------- Columnas ----------
alter table products add column if not exists stock integer;            -- null = sin control
alter table products drop constraint if exists products_stock_check;
alter table products add constraint products_stock_check check (stock is null or stock >= 0);
-- último nivel avisado por mail al dueño ('' | 'ultimas' | 'sin'): un mail por cruce, no por venta
alter table products add column if not exists stock_aviso text not null default '';

-- stock_estado: null = el pedido no tocó stock | reservado | vendido | liberado | devuelto
alter table orders add column if not exists stock_estado text;
-- lo que se descontó de cada pieza: [{ "id": uuid, "qty": n }] (para devolver exactamente eso)
alter table orders add column if not exists stock_items jsonb;
create index if not exists orders_stock_reservado_idx on orders (created_at) where stock_estado = 'reservado';

-- Configuración: «últimas unidades» cuando quedan MENOS de este número (lo cambia el panel → Ajustes)
insert into settings (key, value) values ('stock_umbral', '10'::jsonb) on conflict (key) do nothing;

-- ---------- Historial de movimientos ----------
create table if not exists stock_movimientos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  product_id uuid not null references products (id) on delete cascade,
  cantidad integer not null,                       -- + entra, − sale
  motivo text not null check (motivo in ('venta', 'reserva', 'liberación', 'carga manual', 'devolución')),
  order_id uuid references orders (id) on delete set null,
  stock_despues integer,                           -- cómo quedó la pieza después del movimiento
  by_email text                                    -- quién lo hizo (cargas manuales y devoluciones)
);
create index if not exists stock_mov_prod_idx on stock_movimientos (product_id, created_at desc);
create index if not exists stock_mov_order_idx on stock_movimientos (order_id);

alter table stock_movimientos enable row level security;
-- solo admins lo leen; lo escriben únicamente las funciones de abajo
drop policy if exists "stock admin" on stock_movimientos;
create policy "stock admin" on stock_movimientos for select using (is_admin());

-- ---------- El comprador nunca ve cuántas unidades hay ----------
-- La tienda lee el catálogo desde el servidor y le manda al navegador solo «últimas unidades» o
-- «sin stock». Además, la clave pública (anon) deja de poder leer stock y stock_aviso.
-- (Si en el futuro se agrega una columna a products que tenga que ser pública, sumala acá.)
revoke select on products from anon;
grant select (id, slug, name, category, price, description, image_url, bg, table_color, word, pedestal,
              colors, glow, active, sort, created_at, sale_price, badge, production_time,
              weight_g, height_cm, width_cm, length_cm, ship_estimado) on products to anon;

-- ---------- Ayudas ----------
-- Umbral de «últimas unidades» (ajustes → stock_umbral; 10 si no hay o no es un número)
create or replace function stock_umbral() returns integer
language sql stable security definer set search_path = public as $$
  select greatest(1, least(100000, coalesce((
    select case
      when jsonb_typeof(value) = 'number' then floor((value #>> '{}')::numeric)::integer
      when jsonb_typeof(value) = 'string' and (value #>> '{}') ~ '^\s*\d{1,6}\s*$' then trim(value #>> '{}')::integer
    end
    from settings where key = 'stock_umbral'), 10)));
$$;

-- '' (hay o sin control) | 'ultimas' | 'sin'
create or replace function nivel_stock(s integer, umbral integer) returns text
language sql immutable as $$
  select case when s is null then '' when s <= 0 then 'sin' when s < umbral then 'ultimas' else '' end;
$$;

-- Suma (o resta) unidades a una pieza y lo anota. Si la pieza no tiene control (null), no hace nada.
create or replace function mover_stock(p_product uuid, p_delta integer, p_motivo text, p_order uuid, p_email text default null)
returns integer
language plpgsql security definer set search_path = public as $$
declare s integer;
begin
  update products set stock = stock + p_delta where id = p_product and stock is not null returning stock into s;
  if not found then return null; end if;
  insert into stock_movimientos (product_id, cantidad, motivo, order_id, stock_despues, by_email)
  values (p_product, p_delta, p_motivo, p_order, s, p_email);
  return s;
end $$;
revoke execute on function mover_stock(uuid, integer, text, uuid, text) from public, anon, authenticated;

-- ---------- Reserva al crear el pedido ----------
-- BEFORE INSERT: bloquea las piezas en orden (así dos compras simultáneas no se traban), verifica y
-- descuenta. Si a alguna no le alcanza, no se crea el pedido: error 'sin_stock' y en el detalle
-- [{ id, name, agotada }] (agotada = no queda ninguna; nunca se informa cuántas quedan).
create or replace function stock_reservar() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  it record;
  pr record;
  faltan jsonb := '[]';
  res jsonb := '[]';
begin
  if new.status is distinct from 'pendiente' or new.items is null or jsonb_typeof(new.items) <> 'array' then
    return new;
  end if;
  for it in
    select (e->>'id')::uuid as id, sum(greatest(coalesce((e->>'qty')::integer, 0), 0))::integer as qty
      from jsonb_array_elements(new.items) e
     where (e->>'id') ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
     group by 1
     order by 1
  loop
    select p.id, p.name, p.stock into pr from products p where p.id = it.id for update;
    if not found or pr.stock is null or it.qty <= 0 then continue; end if;
    if pr.stock < it.qty then
      faltan := faltan || jsonb_build_object('id', pr.id, 'name', pr.name, 'agotada', pr.stock = 0);
    else
      res := res || jsonb_build_object('id', pr.id, 'qty', it.qty);
    end if;
  end loop;

  if jsonb_array_length(faltan) > 0 then
    raise exception using errcode = 'P0001', message = 'sin_stock', detail = faltan::text;
  end if;

  if jsonb_array_length(res) > 0 then
    update products p set stock = p.stock - x.qty
      from jsonb_to_recordset(res) as x (id uuid, qty integer)
     where p.id = x.id;
    new.stock_estado := 'reservado';
    new.stock_items := res;
  end if;
  return new;
end $$;

-- AFTER INSERT: anota la reserva (ya existe el pedido para referenciarlo)
create or replace function stock_reservar_anotar() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.stock_estado = 'reservado' and new.stock_items is not null then
    insert into stock_movimientos (product_id, cantidad, motivo, order_id, stock_despues)
    select x.id, -x.qty, 'reserva', new.id, p.stock
      from jsonb_to_recordset(new.stock_items) as x (id uuid, qty integer)
      join products p on p.id = x.id;
  end if;
  return null;
end $$;

drop trigger if exists orders_stock_reservar on orders;
create trigger orders_stock_reservar before insert on orders
  for each row execute function stock_reservar();
drop trigger if exists orders_stock_reservar_anotar on orders;
create trigger orders_stock_reservar_anotar after insert on orders
  for each row execute function stock_reservar_anotar();

-- ---------- Cambios de estado del pedido ----------
-- pagado (o más adelante) → la reserva queda como venta. Si la reserva ya se había liberado (pagó
--   tarde, o pagó después de un rechazo), se vuelve a descontar lo que haya y, si no alcanzó,
--   queda la alerta «revisar stock» (la plata entró: el pedido se respeta, el dueño decide).
-- cancelado / rechazado / devuelto con la reserva todavía tomada → vuelve al stock.
-- (Una VENTA cancelada no vuelve sola: el panel pregunta «¿devolver al stock?»)
create or replace function stock_por_estado() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  r record;
  s integer;
  tomado integer;
  falta boolean := false;
  nuevos jsonb := '[]';
  venta constant text[] := array['pagado', 'en produccion', 'enviado', 'entregado'];
begin
  if new.status is not distinct from old.status or new.stock_estado is null then
    return new;
  end if;

  if new.status = any (venta) and not (coalesce(old.status, '') = any (venta)) then
    if new.stock_estado = 'reservado' then
      update stock_movimientos set motivo = 'venta' where order_id = new.id and motivo = 'reserva';
      new.stock_estado := 'vendido';
    elsif new.stock_estado = 'liberado' then
      for r in select x.id, x.qty from jsonb_to_recordset(new.stock_items) as x (id uuid, qty integer) order by 1 loop
        select stock into s from products where id = r.id for update;
        if not found or s is null then continue; end if;
        tomado := least(s, r.qty);
        if tomado < r.qty then falta := true; end if;
        if tomado > 0 then
          perform mover_stock(r.id, -tomado, 'venta', new.id);
          nuevos := nuevos || jsonb_build_object('id', r.id, 'qty', tomado);
        end if;
      end loop;
      new.stock_items := nuevos;
      new.stock_estado := 'vendido';
      if falta then
        new.alerta := concat_ws(' · ', nullif(new.alerta, ''), 'revisar stock');
      end if;
    end if;
  elsif new.status in ('cancelado', 'rechazado', 'devuelto') and new.stock_estado = 'reservado' then
    for r in select x.id, x.qty from jsonb_to_recordset(new.stock_items) as x (id uuid, qty integer) order by 1 loop
      perform mover_stock(r.id, r.qty, 'liberación', new.id);
    end loop;
    new.stock_estado := 'liberado';
  end if;
  return new;
end $$;

drop trigger if exists orders_stock_estado on orders;
create trigger orders_stock_estado before update of status on orders
  for each row execute function stock_por_estado();

-- ---------- Reservas vencidas ----------
-- Devuelve al stock las reservas de pedidos pendientes cuyo tiempo (reserva_vence_at) ya pasó.
-- Si Mercado Pago avisó que el pago está en proceso (pending / in_process / authorized, por ejemplo
-- un pago en efectivo), se espera hasta 3 días más. También barre pedidos cancelados/rechazados que
-- hayan quedado con la reserva tomada. Una sola liberación a la vez (las demás llamadas salen sin hacer
-- nada) y las piezas se tocan siempre en el mismo orden: no se traba con las compras.
-- Devuelve cuántos pedidos liberó.
create or replace function liberar_reservas_vencidas() returns integer
language plpgsql security definer set search_path = public as $$
declare
  ids uuid[];
  r record;
begin
  if not pg_try_advisory_xact_lock(hashtext('tipificado:liberar_stock')) then
    return 0;
  end if;
  select array_agg(id) into ids from (
    select o.id from orders o
     where o.stock_estado = 'reservado'
       and (
         o.status in ('cancelado', 'rechazado', 'devuelto')
         or (o.status = 'pendiente'
             and coalesce(o.reserva_vence_at, o.created_at + interval '30 minutes') < now()
             and (o.mp_status is null
                  or o.mp_status not in ('pending', 'in_process', 'authorized')
                  or coalesce(o.reserva_vence_at, o.created_at + interval '30 minutes') < now() - interval '3 days'))
       )
     order by o.id
     for update skip locked
  ) v;
  if ids is null then return 0; end if;

  for r in
    select x.id as pid, o.id as oid, x.qty
      from orders o, jsonb_to_recordset(o.stock_items) as x (id uuid, qty integer)
     where o.id = any (ids)
     order by 1, 2
  loop
    perform mover_stock(r.pid, r.qty, 'liberación', r.oid);
  end loop;
  update orders set stock_estado = 'liberado' where id = any (ids);
  return array_length(ids, 1);
end $$;
revoke execute on function liberar_reservas_vencidas() from public, anon, authenticated;
grant execute on function liberar_reservas_vencidas() to service_role;

-- ---------- Panel: cargar stock a mano ----------
-- p_stock null = apagar el control. p_antes = lo que el dueño veía al abrir la pieza: si mientras tanto
-- se vendió o reservó algo, no se pisa (error 'stock_cambio') y el panel le pide revisar el número.
-- Una carga manual no manda mail (el dueño ya sabe): deja el aviso al día.
create or replace function fijar_stock(p_product uuid, p_stock integer, p_antes integer) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  pr products%rowtype;
  delta integer;
  quien text := lower(auth.jwt() ->> 'email');
begin
  if not is_admin() then raise exception 'no_autorizado'; end if;
  if p_stock is not null and (p_stock < 0 or p_stock > 100000) then raise exception 'stock_invalido'; end if;
  select * into pr from products where id = p_product for update;
  if not found then raise exception 'pieza_inexistente'; end if;
  if pr.stock is distinct from p_antes then raise exception 'stock_cambio'; end if;

  if p_stock is null then
    update products set stock = null, stock_aviso = '' where id = p_product;
  else
    delta := p_stock - coalesce(pr.stock, 0);
    update products set stock = p_stock, stock_aviso = nivel_stock(p_stock, stock_umbral()) where id = p_product;
    if delta <> 0 or pr.stock is null then
      insert into stock_movimientos (product_id, cantidad, motivo, stock_despues, by_email)
      values (p_product, delta, 'carga manual', p_stock, quien);
    end if;
  end if;
  return jsonb_build_object('ok', true, 'stock', p_stock);
end $$;
revoke execute on function fijar_stock(uuid, integer, integer) from public, anon;
grant execute on function fijar_stock(uuid, integer, integer) to authenticated;

-- ---------- Panel: devolver al stock un pedido cancelado ----------
-- vendido → 'devolución' (+) · reservado → 'liberación' (+). Una sola vez por pedido.
create or replace function devolver_stock_pedido(p_order uuid) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  o orders%rowtype;
  r record;
  quien text := lower(auth.jwt() ->> 'email');
begin
  if not is_admin() then raise exception 'no_autorizado'; end if;
  select * into o from orders where id = p_order for update;
  if not found then return jsonb_build_object('ok', false, 'motivo', 'pedido_inexistente'); end if;
  if o.stock_estado not in ('vendido', 'reservado') or o.stock_items is null then
    return jsonb_build_object('ok', false, 'motivo', 'nada_para_devolver', 'estado', o.stock_estado);
  end if;
  for r in select x.id, x.qty from jsonb_to_recordset(o.stock_items) as x (id uuid, qty integer) order by 1 loop
    perform mover_stock(r.id, r.qty, case when o.stock_estado = 'vendido' then 'devolución' else 'liberación' end, o.id, quien);
  end loop;
  update orders set stock_estado = case when o.stock_estado = 'vendido' then 'devuelto' else 'liberado' end where id = p_order;
  return jsonb_build_object('ok', true);
end $$;
revoke execute on function devolver_stock_pedido(uuid) from public, anon;
grant execute on function devolver_stock_pedido(uuid) to authenticated;

-- ---------- Mails al dueño: un mail por cruce ----------
-- Pone al día el nivel avisado de cada pieza y devuelve solo las que EMPEORARON (entraron en
-- «últimas unidades» o se quedaron sin stock). Si dos llamadas corren juntas, la segunda ya ve el
-- nivel actualizado y no devuelve nada: no hay mails repetidos. Lo llama el servidor después de una venta.
create or replace function tomar_avisos_stock()
returns table (id uuid, name text, stock integer, nivel text)
language sql security definer set search_path = public as $$
  with u as (select stock_umbral() as umbral),
  n as (
    select p.id, p.stock_aviso as antes, nivel_stock(p.stock, u.umbral) as nivel
      from products p, u
     where p.stock is not null or p.stock_aviso <> ''
  ),
  cambios as (
    update products p set stock_aviso = n.nivel
      from n
     where p.id = n.id and p.stock_aviso is distinct from n.nivel
    returning p.id, p.name, p.stock, n.nivel, n.antes
  )
  select c.id, c.name, c.stock, c.nivel from cambios c
   where (case c.nivel when 'sin' then 2 when 'ultimas' then 1 else 0 end)
       > (case c.antes when 'sin' then 2 when 'ultimas' then 1 else 0 end);
$$;
revoke execute on function tomar_avisos_stock() from public, anon, authenticated;
grant execute on function tomar_avisos_stock() to service_role;

-- ---------- Liberación automática cada 5 minutos (si el proyecto tiene pg_cron) ----------
do $$
begin
  if exists (select 1 from pg_available_extensions where name = 'pg_cron') then
    create extension if not exists pg_cron;
    if exists (select 1 from cron.job where jobname = 'liberar-stock') then
      perform cron.unschedule('liberar-stock');
    end if;
    perform cron.schedule('liberar-stock', '*/5 * * * *', 'select public.liberar_reservas_vencidas()');
  end if;
exception when others then
  null; -- sin pg_cron: liberan el checkout, la tienda al leer el catálogo y el cron de Vercel
end $$;

