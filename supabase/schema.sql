-- (versión anterior: el cupón se gastaba al crear el pedido; ya no se usa)
drop function if exists usar_cupon(text);

-- Crea el pedido de forma atómica. Si tiene cupón, bloquea el cupón y respeta el límite contando:
--   usos confirmados (pagos aprobados) + pedidos pendientes cuya reserva todavía no venció.
-- p_vence = cuándo vence la reserva (lo manda api/checkout, el mismo instante que expiration_date_to de MP).
-- Solo la llama el servidor (api/checkout).
-- (versión anterior, sin p_vence: se borra para que no queden dos funciones)
drop function if exists crear_pedido(text, text, text, jsonb, integer, integer, text, jsonb, integer, integer);
create or replace function crear_pedido(
  p_customer_name text, p_contact text, p_note text, p_items jsonb,
  p_subtotal integer, p_discount integer, p_coupon_code text,
  p_shipping jsonb, p_shipping_cost integer, p_total integer,
  p_vence timestamptz default null
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  c coupons%rowtype;
  reservados integer;
  r jsonb;
begin
  if p_coupon_code is not null then
    select * into c from coupons where code = upper(p_coupon_code) for update;
    if not found or not c.active
       or (c.expires_at is not null and c.expires_at < (now() at time zone 'America/Argentina/Buenos_Aires')::date) then
      raise exception 'cupon_no_disponible';
    end if;
    if c.max_uses is not null then
      select count(*) into reservados from orders o
       where o.coupon_code = c.code and o.status = 'pendiente' and not o.coupon_counted
         and coalesce(o.reserva_vence_at, o.created_at + interval '30 minutes') > now();
      if c.uses + reservados >= c.max_uses then
        raise exception 'cupon_no_disponible';
      end if;
    end if;
  end if;

  insert into orders (customer_name, contact, note, items, subtotal, discount, coupon_code,
                      shipping, shipping_cost, total, status, channel, reserva_vence_at)
  values (p_customer_name, coalesce(p_contact, ''), coalesce(p_note, ''), p_items, p_subtotal, p_discount,
          case when p_coupon_code is null then null else c.code end,
          p_shipping, p_shipping_cost, p_total, 'pendiente', 'mercadopago',
          coalesce(p_vence, now() + interval '30 minutes'))
  returning jsonb_build_object('id', orders.id, 'number', orders.number) into r;
  return r;
end $$;
revoke execute on function crear_pedido(text, text, text, jsonb, integer, integer, text, jsonb, integer, integer, timestamptz) from public, anon, authenticated;
grant execute on function crear_pedido(text, text, text, jsonb, integer, integer, text, jsonb, integer, integer, timestamptz) to service_role;

-- Aplica el estado de un pago de Mercado Pago a su pedido. Idempotente: si llega dos veces el mismo
-- aviso, no cambia nada ni cuenta el cupón dos veces.
--   aprobado            → pedido "pagado", suma 1 uso al cupón, marca paid_at (avisar = true la primera vez)
--   rechazado/cancelado → si el cupón estaba contado, lo libera
--   devuelto/contracargo→ pedido "devuelto" y libera el cupón
-- No pisa los estados que el dueño ya avanzó a mano (en producción, enviado, entregado), salvo una devolución.
create or replace function aplicar_pago(p_order uuid, p_payment_id text, p_mp_status text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  o orders%rowtype;
  nuevo text;
  contado boolean;
  alerta_nueva text;
  aprobado boolean := p_mp_status = 'approved';
  devuelto boolean := p_mp_status in ('refunded', 'charged_back');
  liberar boolean := p_mp_status in ('rejected', 'cancelled', 'refunded', 'charged_back');
begin
  select * into o from orders where id = p_order for update;
  if not found then
    return jsonb_build_object('ok', false, 'motivo', 'pedido_inexistente');
  end if;

  -- un aviso de OTRO intento de pago (por ejemplo, uno rechazado antes) no pisa un pago ya aprobado
  if o.mp_status = 'approved' and o.payment_id is distinct from p_payment_id and not aprobado then
    return jsonb_build_object('ok', true, 'cambio', false, 'motivo', 'otro_pago_ya_aprobado', 'estado', o.status, 'numero', o.number);
  end if;

  nuevo := case p_mp_status
    when 'approved' then 'pagado'
    when 'pending' then 'pendiente'
    when 'in_process' then 'pendiente'
    when 'authorized' then 'pendiente'
    when 'rejected' then 'rechazado'
    when 'cancelled' then 'cancelado'
    when 'refunded' then 'devuelto'
    when 'charged_back' then 'devuelto'
    else o.status
  end;
  if o.status in ('en produccion', 'enviado', 'entregado') and not devuelto then
    nuevo := o.status;
  end if;

  contado := o.coupon_counted;
  -- Pago aprobado con cupón cuya reserva ya venció: la plata entró, así que se acepta igual,
  -- pero queda la alerta «revisar cupón» (el cupón pudo haberse agotado mientras tanto).
  alerta_nueva := o.alerta;
  if aprobado and o.coupon_code is not null and not o.coupon_counted
     and now() > coalesce(o.reserva_vence_at, o.created_at + interval '30 minutes') then
    alerta_nueva := 'revisar cupón';
  end if;
  if o.coupon_code is not null then
    if aprobado and not contado then
      update coupons set uses = uses + 1 where code = o.coupon_code;
      contado := true;
    elsif liberar and contado then
      update coupons set uses = greatest(uses - 1, 0) where code = o.coupon_code;
      contado := false;
    end if;
  end if;

  update orders set
    payment_id = p_payment_id,
    mp_status = p_mp_status,
    status = nuevo,
    coupon_counted = contado,
    alerta = alerta_nueva,
    paid_at = case when aprobado then coalesce(o.paid_at, now()) else o.paid_at end
  where id = p_order;

  return jsonb_build_object(
    'ok', true,
    'cambio', (nuevo is distinct from o.status) or (p_mp_status is distinct from o.mp_status),
    'anterior', o.status,
    'estado', nuevo,
    'avisar', aprobado and o.paid_at is null,
    'numero', o.number
  );
end $$;
revoke execute on function aplicar_pago(uuid, text, text) from public, anon, authenticated;
grant execute on function aplicar_pago(uuid, text, text) to service_role;

