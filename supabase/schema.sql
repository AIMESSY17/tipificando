-- Limpieza automática: se borra todo lo de más de 30 días.
-- Si pg_cron está disponible, corre una vez al día. Si no, se borra al insertar un aviso nuevo (trigger).
create or replace function limpiar_mp_webhooks() returns void
language sql security definer set search_path = public as $$
  delete from mp_webhooks where created_at < now() - interval '30 days';
$$;
revoke execute on function limpiar_mp_webhooks() from public, anon, authenticated;

create or replace function limpiar_mp_webhooks_trg() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  delete from mp_webhooks where created_at < now() - interval '30 days';
  return null;
end $$;

do $$
declare con_cron boolean := false;
begin
  begin
    if exists (select 1 from pg_available_extensions where name = 'pg_cron') then
      create extension if not exists pg_cron;
      if exists (select 1 from cron.job where jobname = 'limpiar-mp-webhooks') then
        perform cron.unschedule('limpiar-mp-webhooks');
      end if;
      perform cron.schedule('limpiar-mp-webhooks', '17 6 * * *', 'select public.limpiar_mp_webhooks()');
      con_cron := true;
    end if;
  exception when others then
    con_cron := false;  -- sin permisos o sin pg_cron: se usa el trigger
  end;

  drop trigger if exists mp_webhooks_limpieza on mp_webhooks;
  if not con_cron then
    create trigger mp_webhooks_limpieza after insert on mp_webhooks
      for each statement execute function limpiar_mp_webhooks_trg();
  end if;
end $$;

-- ---------- Límite anti-abuso del checkout (intentos por IP) ----------
create table if not exists checkout_intentos (
  id bigint generated by default as identity primary key,
  ip text not null,          -- huella (hash) de la IP, no la IP en sí
  created_at timestamptz not null default now()
);
create index if not exists checkout_intentos_ip_idx on checkout_intentos (ip, created_at desc);

-- true si la IP todavía puede intentar (y registra el intento); false si pasó el límite
create or replace function permitir_intento(p_ip text, p_max integer, p_minutos integer) returns boolean
language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  perform pg_advisory_xact_lock(hashtext('checkout:' || p_ip));
  -- limpieza de lo viejo (de paso)
  delete from checkout_intentos where created_at < now() - interval '1 day';
  select count(*) into n from checkout_intentos
   where ip = p_ip and created_at > now() - make_interval(mins => p_minutos);
  if n >= p_max then
    return false;
  end if;
  insert into checkout_intentos (ip) values (p_ip);
  return true;
end $$;
revoke execute on function permitir_intento(text, integer, integer) from public, anon, authenticated;
grant execute on function permitir_intento(text, integer, integer) to service_role;

